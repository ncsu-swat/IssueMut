#!/bin/bash

if [ $# -ne 1 ]; then
    echo "Usage: $0 <file>"
    exit 1
fi

file="$1"

sed -i -E '
:a
s/(([^|&()[:space:]]+|[(][^)]*[)])\s*(==|!=|<=|>=|<|>)\s*([^|&()[:space:]]+|[(][^)]*[)]))(\s*)\|\|(\s*)(([^|&()[:space:]]+|[(][^)]*[)])\s*(==|!=|<=|>=|<|>)\s*([^|&()[:space:]]+|[(][^)]*[)]))/\1\5|\6\7/g
t a
' "$file"