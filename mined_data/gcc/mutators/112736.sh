#!/bin/bash

if [ $# -ne 1 ]; then
    echo "Usage: $0 <file>"
    exit 1
fi

file="$1"

sed -i -E '
:a; N; $!ba; s/\n/þ/g

s|(\s*for\s*\([^)]*\)\s*)\{\s*þ\s*([^{};]*\S)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*([^;]*);\s*þ(\s*for\s*\([^)]*\)\s*)\{\s*þ([^}]*)\b\3\b([^}]*)\}\s*þ\s*\}|\1þ\5{þ\6\4\7}|g
s|(\s*for\s*\([^)]*\)\s*)\{\s*þ\s*([^{};]*\S)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*([^;]*);\s*þ(\s*for\s*\([^)]*\)\s*)([^;]*)\b\3\b([^;]*;)\s*þ\s*\}|\1þ\5\6\4\7|g

s/þ/\n/g
' "$file"