#!/bin/bash

if [ $# -ne 1 ]; then
    echo "Usage: $0 <file>"
    exit 1
fi

file="$1"

sed -i -z -E 's|([a-zA-Z0-9_]+\s+[a-zA-Z0-9_]+\s*\([^,]*\b([a-zA-Z0-9_]+)\b\s*,\s*[^)]*\b([a-zA-Z0-9_]+)\b\s*\))(\s*)\{\s*\2\[[0-9]+\]\s*=\s*\2\[[0-9]+\]\s*([-+*/&^|])\s*\3\[[0-9]+\];(\s*\2\[[0-9]+\]\s*=\s*\2\[[0-9]+\]\s*\5\s*\3\[[0-9]+\];)*\s*return\s+\2;\s*\}|\1\4{ return \2 \5 \3; }|g' "$file"